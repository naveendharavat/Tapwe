-- Tapwe schema for Supabase (Postgres). Mirrors tapwe-server/src/database/migrations/1792753135719-Init.ts.

create type users_role_enum as enum ('owner', 'admin');
create type cards_status_enum as enum ('draft', 'active', 'paused');
create type cards_destination_type_enum as enum ('profile', 'url', 'menu', 'form');
create type card_requests_status_enum as enum ('new', 'contacted', 'fulfilled');
create type change_requests_status_enum as enum ('open', 'done');

create table users (
  id integer generated by default as identity primary key,
  name varchar(120) not null,
  email varchar(190) not null unique,
  password_hash varchar(100) not null,
  role users_role_enum not null default 'owner',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table cards (
  code varchar(6) primary key,
  user_id integer null references users (id) on delete set null,
  owner_email varchar(190) null,
  name varchar(120) not null,
  status cards_status_enum not null default 'draft',
  destination_type cards_destination_type_enum not null default 'profile',
  destination_url varchar(500) null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz null
);
create index cards_user_id_idx on cards (user_id);
create index cards_owner_email_idx on cards (owner_email);

create table tap_events (
  id integer generated by default as identity primary key,
  card_code varchar(6) not null references cards (code) on delete cascade,
  happened_at timestamptz not null default now(),
  user_agent varchar(300) null
);
create index tap_events_card_code_happened_at_idx on tap_events (card_code, happened_at);

create table card_requests (
  id integer generated by default as identity primary key,
  name varchar(120) not null,
  business_name varchar(120) not null,
  email varchar(190) not null,
  phone varchar(10) not null,
  business_type varchar(60) not null,
  quantity varchar(30) not null,
  destinations jsonb not null,
  city varchar(120) null,
  note text null,
  agreed boolean not null default false,
  status card_requests_status_enum not null default 'new',
  created_at timestamptz not null default now()
);

create table change_requests (
  id integer generated by default as identity primary key,
  card_code varchar(6) not null references cards (code) on delete cascade,
  message varchar(500) not null,
  status change_requests_status_enum not null default 'open',
  created_at timestamptz not null default now()
);
create index change_requests_card_code_idx on change_requests (card_code);

create table profiles (
  id integer generated by default as identity primary key,
  user_id integer not null unique references users (id) on delete cascade,
  business_name varchar(120) null,
  description varchar(200) null,
  phone varchar(20) null,
  website varchar(500) null,
  updated_at timestamptz not null default now()
);

-- Postgres has no ON UPDATE CURRENT_TIMESTAMP, so a trigger keeps updated_at fresh.
create function set_updated_at() returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger users_set_updated_at before update on users for each row execute function set_updated_at();
create trigger cards_set_updated_at before update on cards for each row execute function set_updated_at();
create trigger profiles_set_updated_at before update on profiles for each row execute function set_updated_at();

-- Only the NestJS API touches these tables; RLS with no policies blocks Supabase's public REST API (anon key) from reading them.
alter table users enable row level security;
alter table cards enable row level security;
alter table tap_events enable row level security;
alter table card_requests enable row level security;
alter table change_requests enable row level security;
alter table profiles enable row level security;
